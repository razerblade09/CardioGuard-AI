"""
Recover recorded CardioGuard heart rates from Firebase.

Every reading the API processes is written to readings/{patient_id} with its
heart_rate value, so the heart rates measured during participant testing are
already stored and do not need to be re-collected. This script pulls them back
out so they can be paired with the reference instrument's pulse rate.

patient_003 is the ghost/demo patient generated by the simulator in cloud_api.py.
Its readings are synthetic and are excluded by default -- never report them as
participant data.

Usage:
    python clinical_testing/fetch_hr_from_firebase.py --list
    python clinical_testing/fetch_hr_from_firebase.py --patient patient_001
    python clinical_testing/fetch_hr_from_firebase.py --patient patient_001 --date 2026-08-02
"""

import argparse
import csv
import datetime
import json
import os
import statistics
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS_DIR = os.path.join(BASE_DIR, "clinical_testing", "results")
CRED_PATH = os.path.join(BASE_DIR, "firebase_credentials.json")

GHOST_PATIENT_ID = "patient_003"   # simulated demo patient -- not a real participant


def connect():
    try:
        import firebase_admin
        from firebase_admin import credentials, db
    except ImportError:
        sys.exit("firebase-admin not installed.  pip install firebase-admin")

    db_url = os.getenv("FIREBASE_DB_URL", "")
    if not db_url:
        # fall back to the project id in the service-account file
        if os.path.exists(CRED_PATH):
            with open(CRED_PATH, encoding="utf-8") as f:
                project = json.load(f).get("project_id", "")
            if project:
                db_url = f"https://{project}-default-rtdb.firebaseio.com"
    if not db_url:
        sys.exit("Set FIREBASE_DB_URL, or place firebase_credentials.json at the project root.")

    if not os.path.exists(CRED_PATH):
        sys.exit(f"Service-account key not found: {CRED_PATH}")

    if not firebase_admin._apps:
        firebase_admin.initialize_app(
            credentials.Certificate(CRED_PATH), {"databaseURL": db_url})
    print(f"Connected to {db_url}\n")
    return db


def list_patients(db):
    node = db.reference("readings").get(shallow=True) or {}
    if not node:
        print("No readings found in the database.")
        return
    print("Patients with stored readings:\n")
    for pid in sorted(node):
        n = len(db.reference(f"readings/{pid}").get(shallow=True) or {})
        tag = "  <- SIMULATED, do not use as participant data" if pid == GHOST_PATIENT_ID else ""
        print(f"  {pid:<16} {n:>7,} readings{tag}")


def fetch(db, patient_id, date_filter=None):
    if patient_id == GHOST_PATIENT_ID:
        sys.exit(f"{GHOST_PATIENT_ID} is the simulated demo patient. Its readings are "
                 f"synthetic and must not be reported as participant data.")

    raw = db.reference(f"readings/{patient_id}").get() or {}
    if not raw:
        sys.exit(f"No readings stored for {patient_id}.")

    rows = []
    for key, r in raw.items():
        if not isinstance(r, dict):
            continue
        hr = r.get("heart_rate")
        if hr in (None, 0):
            continue                      # buffer had too few R-peaks to estimate
        ts = str(r.get("timestamp", ""))
        if date_filter and not ts.startswith(date_filter):
            continue
        rows.append({
            "timestamp": ts,
            "heart_rate": int(hr),
            "prediction": r.get("prediction", ""),
            "confidence": r.get("confidence", ""),
            "device_id": r.get("device_id", ""),
        })

    rows.sort(key=lambda r: r["timestamp"])
    return rows


def summarize(patient_id, rows):
    if not rows:
        print("No readings matched that filter.")
        return

    hrs = [r["heart_rate"] for r in rows]
    print(f"{patient_id}: {len(rows):,} readings with a heart rate\n")
    print(f"  First reading : {rows[0]['timestamp']}")
    print(f"  Last reading  : {rows[-1]['timestamp']}")
    print(f"  Mean          : {statistics.mean(hrs):.1f} bpm")
    print(f"  Median        : {statistics.median(hrs):.1f} bpm")
    if len(hrs) > 1:
        print(f"  Std deviation : {statistics.stdev(hrs):.1f} bpm")
    print(f"  Range         : {min(hrs)} - {max(hrs)} bpm")

    preds = {}
    for r in rows:
        preds[r["prediction"]] = preds.get(r["prediction"], 0) + 1
    print("\n  Predictions:")
    for name, count in sorted(preds.items(), key=lambda kv: -kv[1]):
        print(f"    {name or '(none)':<14} {count:>7,}  ({100.0 * count / len(rows):5.1f}%)")

    # group by calendar day so testing sessions are easy to identify
    days = {}
    for r in rows:
        days.setdefault(r["timestamp"][:10], []).append(r["heart_rate"])
    print("\n  By date:")
    for day in sorted(days):
        v = days[day]
        print(f"    {day}   n={len(v):>6,}   median {statistics.median(v):5.1f} bpm"
              f"   range {min(v)}-{max(v)}")

    if statistics.median(hrs) > 100:
        print("\n  NOTE: median above 100 bpm. For a resting subject this suggests "
              "R-peak double-counting rather than genuine tachycardia -- worth "
              "checking before reporting.")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--list", action="store_true", help="list patients that have readings")
    ap.add_argument("--patient", help="patient id, e.g. patient_001")
    ap.add_argument("--date", help="keep only readings from this date (YYYY-MM-DD)")
    ap.add_argument("--csv", action="store_true", help="also write the readings to a CSV")
    args = ap.parse_args()

    db = connect()

    if args.list or not args.patient:
        list_patients(db)
        if not args.patient:
            print("\nRe-run with --patient <id> to pull that patient's heart rates.")
        return

    rows = fetch(db, args.patient, args.date)
    summarize(args.patient, rows)

    if args.csv and rows:
        os.makedirs(RESULTS_DIR, exist_ok=True)
        suffix = f"_{args.date}" if args.date else ""
        out = os.path.join(RESULTS_DIR, f"hr_{args.patient}{suffix}.csv")
        with open(out, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
        print(f"\nWrote {len(rows):,} rows -> {out}")


if __name__ == "__main__":
    main()
